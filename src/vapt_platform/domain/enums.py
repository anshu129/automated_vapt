def default_safety_for(cap: Capability) -> SafetyClass:
    """Heuristic safety class when not explicitly mapped."""
    if cap in DEFAULT_SAFETY:
        return DEFAULT_SAFETY[cap]
    name = cap.value
    if "PASSIVE" in name or cap in (
        Capability.PASSIVE_SUBDOMAIN_DISCOVERY,
        Capability.CERTIFICATE_TRANSPARENCY_DISCOVERY,
        Capability.HISTORICAL_URL_DISCOVERY,
        Capability.EXTERNAL_ASSET_ENRICHMENT,
    ):
        return SafetyClass.PASSIVE
    if any(
        x in name
        for x in ("BRUTEFORCE", "ACTIVE", "MASS", "HIGH_VOLUME", "DESTRUCTIVE")
    ):
        return SafetyClass.STATE_CHANGING
    return SafetyClass.LOW_IMPACT


